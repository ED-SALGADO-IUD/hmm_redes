"""Reproducible categorical HMM simulation for network-quality regimes.

All data generated by this script are synthetic. The hidden states are used only
as ground truth to evaluate sequence decoding under controlled conditions.
"""
from __future__ import annotations
import csv
import json
import platform
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
FIGURES = ROOT / "figures"
DATA.mkdir(exist_ok=True)
FIGURES.mkdir(exist_ok=True)

STATE_NAMES = ["Stable", "Degraded", "Outage"]
OBSERVATION_NAMES = [
    "L-low", "L-moderate", "L-high",
    "M-low", "M-moderate", "M-high",
    "H-low", "H-moderate", "H-high",
]

PI_BASE = np.array([0.80, 0.18, 0.02], dtype=float)
A_BASE = np.array([
    [0.94, 0.055, 0.005],
    [0.20, 0.720, 0.080],
    [0.10, 0.250, 0.650],
], dtype=float)
B_BASE = np.array([
    [0.72, 0.07, 0.01, 0.12, 0.05, 0.01, 0.01, 0.01, 0.00],
    [0.10, 0.12, 0.03, 0.20, 0.25, 0.08, 0.05, 0.10, 0.07],
    [0.01, 0.04, 0.15, 0.04, 0.12, 0.26, 0.02, 0.10, 0.26],
], dtype=float)


def validate_model(pi: np.ndarray, A: np.ndarray, B: np.ndarray) -> None:
    for name, x in (("pi", pi), ("A", A), ("B", B)):
        if np.any(x < 0) or not np.allclose(x.sum(axis=-1), 1.0):
            raise ValueError(f"Invalid probability rows in {name}")
    if A.shape != (3, 3) or B.shape != (3, 9) or pi.shape != (3,):
        raise ValueError("Expected shapes pi=(3,), A=(3,3), B=(3,9)")


def sample_sequence(rng: np.random.Generator, pi: np.ndarray,
                    A: np.ndarray, B: np.ndarray, length: int):
    states = np.empty(length, dtype=int)
    observations = np.empty(length, dtype=int)
    states[0] = rng.choice(len(pi), p=pi)
    observations[0] = rng.choice(B.shape[1], p=B[states[0]])
    for t in range(1, length):
        states[t] = rng.choice(A.shape[0], p=A[states[t - 1]])
        observations[t] = rng.choice(B.shape[1], p=B[states[t]])
    return states, observations


def forward_log_likelihood(obs: np.ndarray, pi: np.ndarray,
                           A: np.ndarray, B: np.ndarray) -> float:
    """Stable log P(observations | model), using per-step scaling."""
    alpha = pi * B[:, obs[0]]
    scale = alpha.sum()
    if scale <= 0:
        return -np.inf
    log_likelihood = np.log(scale)
    alpha /= scale
    for symbol in obs[1:]:
        alpha = (alpha @ A) * B[:, symbol]
        scale = alpha.sum()
        if scale <= 0:
            return -np.inf
        log_likelihood += np.log(scale)
        alpha /= scale
    return float(log_likelihood)


def viterbi(obs: np.ndarray, pi: np.ndarray,
            A: np.ndarray, B: np.ndarray) -> np.ndarray:
    """Most likely hidden-state path in log space."""
    n_states = len(pi)
    log_A = np.log(np.maximum(A, 1e-300))
    log_B = np.log(np.maximum(B, 1e-300))
    delta = np.empty((len(obs), n_states))
    back = np.zeros((len(obs), n_states), dtype=int)
    delta[0] = np.log(np.maximum(pi, 1e-300)) + log_B[:, obs[0]]
    for t in range(1, len(obs)):
        scores = delta[t - 1][:, None] + log_A
        back[t] = np.argmax(scores, axis=0)
        delta[t] = np.max(scores, axis=0) + log_B[:, obs[t]]
    path = np.empty(len(obs), dtype=int)
    path[-1] = int(np.argmax(delta[-1]))
    for t in range(len(obs) - 2, -1, -1):
        path[t] = back[t + 1, path[t + 1]]
    return path


def macro_f1(y_true: np.ndarray, y_pred: np.ndarray) -> float:
    scores = []
    for state in range(3):
        tp = np.sum((y_true == state) & (y_pred == state))
        fp = np.sum((y_true != state) & (y_pred == state))
        fn = np.sum((y_true == state) & (y_pred != state))
        denom = 2 * tp + fp + fn
        scores.append(0.0 if denom == 0 else 2 * tp / denom)
    return float(np.mean(scores))


def metrics(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, float]:
    outage = 2
    stable = 0
    true_outage = y_true == outage
    pred_outage = y_pred == outage
    true_stable = y_true == stable
    pred_unhealthy = y_pred > stable
    return {
        "accuracy": float(np.mean(y_true == y_pred)),
        "macro_f1": macro_f1(y_true, y_pred),
        "outage_recall": float(np.sum(true_outage & pred_outage) / max(1, np.sum(true_outage))),
        "stable_false_alarm_rate": float(np.sum(true_stable & pred_unhealthy) / max(1, np.sum(true_stable))),
    }


def scenarios() -> dict[str, tuple[np.ndarray, np.ndarray, np.ndarray]]:
    # Scenario 2: more persistent hidden regimes, retaining the same emissions.
    A_persistent = np.array([
        [0.970, 0.028, 0.002],
        [0.100, 0.840, 0.060],
        [0.040, 0.160, 0.800],
    ])
    # Scenario 3: overlapping emissions (55% uniform noise mixed into each row).
    B_overlap = 0.45 * B_BASE + 0.55 * np.full_like(B_BASE, 1 / B_BASE.shape[1])
    # Scenario 4: initial state stress test; transition/emission matrices unchanged.
    PI_STRESS = np.array([0.45, 0.40, 0.15])
    return {
        "S1_baseline": (PI_BASE.copy(), A_BASE.copy(), B_BASE.copy()),
        "S2_persistent_states": (PI_BASE.copy(), A_persistent, B_BASE.copy()),
        "S3_overlapping_emissions": (PI_BASE.copy(), A_BASE.copy(), B_overlap),
        "S4_initial_state_stress": (PI_STRESS, A_BASE.copy(), B_BASE.copy()),
    }


def stationary_distribution(A: np.ndarray) -> np.ndarray:
    vals, vecs = np.linalg.eig(A.T)
    idx = int(np.argmin(np.abs(vals - 1.0)))
    v = np.real(vecs[:, idx])
    v = np.abs(v)
    return v / v.sum()


def confidence_interval(values: np.ndarray) -> tuple[float, float]:
    mean = float(np.mean(values))
    se = float(np.std(values, ddof=1) / np.sqrt(len(values)))
    return mean - 1.96 * se, mean + 1.96 * se


def main() -> None:
    n_replicates = 400
    sequence_length = 300
    base_seed = 20261109
    records = []
    confusion = {name: np.zeros((3, 3), dtype=np.int64) for name in scenarios()}
    ll_samples = {name: [] for name in scenarios()}
    for scenario_index, (scenario_name, (pi, A, B)) in enumerate(scenarios().items()):
        validate_model(pi, A, B)
        for replicate in range(n_replicates):
            seed = base_seed + scenario_index * 100_000 + replicate
            rng = np.random.default_rng(seed)
            true_states, obs = sample_sequence(rng, pi, A, B, sequence_length)
            predicted = viterbi(obs, pi, A, B)
            row = {"scenario": scenario_name, "replicate": replicate,
                   "seed": seed, **metrics(true_states, predicted),
                   "log_likelihood": forward_log_likelihood(obs, pi, A, B)}
            records.append(row)
            for t, p in zip(true_states, predicted):
                confusion[scenario_name][t, p] += 1
            ll_samples[scenario_name].append(row["log_likelihood"])

    raw = pd.DataFrame(records)
    raw.to_csv(DATA / "replicate_metrics.csv", index=False, float_format="%.8f")
    metric_names = ["accuracy", "macro_f1", "outage_recall", "stable_false_alarm_rate"]
    summary_rows = []
    for scenario_name in raw["scenario"].unique():
        block = raw[raw.scenario == scenario_name]
        for metric_name in metric_names:
            values = block[metric_name].to_numpy()
            ci_low, ci_high = confidence_interval(values)
            summary_rows.append({
                "scenario": scenario_name, "metric": metric_name,
                "mean": np.mean(values), "sd": np.std(values, ddof=1),
                "min": np.min(values), "max": np.max(values),
                "ci95_low": ci_low, "ci95_high": ci_high,
            })
    summary = pd.DataFrame(summary_rows)
    summary.to_csv(DATA / "summary_metrics.csv", index=False, float_format="%.6f")

    model_out = {}
    for name, (pi, A, B) in scenarios().items():
        model_out[name] = {
            "initial_distribution_pi": pi.tolist(),
            "transition_matrix_A": A.tolist(),
            "emission_matrix_B": B.tolist(),
            "stationary_distribution": stationary_distribution(A).tolist(),
        }
    (DATA / "model_parameters.json").write_text(json.dumps({
        "states": STATE_NAMES, "observations": OBSERVATION_NAMES,
        "replicates_per_scenario": n_replicates,
        "sequence_length": sequence_length, "base_seed": base_seed,
        "scenarios": model_out,
        "environment": {"python": platform.python_version(),
                        "numpy": np.__version__, "pandas": pd.__version__,
                        "matplotlib": plt.matplotlib.__version__},
    }, indent=2), encoding="utf-8")

    cm = confusion["S1_baseline"].astype(float)
    cm = cm / cm.sum(axis=1, keepdims=True)
    fig, ax = plt.subplots(figsize=(6.4, 5.1))
    im = ax.imshow(cm, cmap="Blues", vmin=0, vmax=1)
    ax.set_xticks(range(3), STATE_NAMES, rotation=15)
    ax.set_yticks(range(3), STATE_NAMES)
    ax.set_xlabel("Predicted hidden regime")
    ax.set_ylabel("Simulated true regime")
    ax.set_title("Baseline scenario: normalized state confusion")
    for i in range(3):
        for j in range(3):
            ax.text(j, i, f"{cm[i,j]:.3f}", ha="center", va="center",
                    color="white" if cm[i,j] > 0.55 else "black", fontsize=10)
    fig.colorbar(im, ax=ax, label="Row proportion")
    fig.tight_layout()
    fig.savefig(FIGURES / "fig1_baseline_confusion.png", dpi=300, bbox_inches="tight")
    plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(11, 4.8))
    order = list(scenarios().keys())
    labels = ["Baseline", "Persistent\nstates", "Overlapping\nemissions", "Initial-state\nstress"]
    for ax, metric_name, title in zip(
        axes, ["macro_f1", "outage_recall"], ["Macro F1", "Outage recall"]):
        values = [raw[raw.scenario == key][metric_name].to_numpy() for key in order]
        ax.boxplot(values, tick_labels=labels, showfliers=False, patch_artist=True,
                   boxprops={"facecolor": "#B9D8F2"}, medianprops={"color": "#14324A", "linewidth": 1.5})
        ax.set_ylabel(title)
        ax.set_ylim(0, 1.02)
        ax.set_title(title + " by simulation scenario")
        ax.grid(axis="y", alpha=0.25)
    fig.tight_layout()
    fig.savefig(FIGURES / "fig2_scenario_sensitivity.png", dpi=300, bbox_inches="tight")
    plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(11, 4.8))
    for ax, mat, ticks, title in [
        (axes[0], A_BASE, STATE_NAMES, "Transition matrix A"),
        (axes[1], B_BASE, OBSERVATION_NAMES, "Emission matrix B"),
    ]:
        im = ax.imshow(mat, cmap="YlGnBu", vmin=0, vmax=max(0.8, mat.max()))
        ax.set_xticks(range(mat.shape[1]), ticks, rotation=45, ha="right")
        ax.set_yticks(range(mat.shape[0]), STATE_NAMES)
        ax.set_title(title)
        for i in range(mat.shape[0]):
            for j in range(mat.shape[1]):
                ax.text(j, i, f"{mat[i,j]:.2f}", ha="center", va="center", fontsize=7)
        fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    fig.tight_layout()
    fig.savefig(FIGURES / "fig3_reference_matrices.png", dpi=300, bbox_inches="tight")
    plt.close(fig)

    print(summary.to_string(index=False, float_format=lambda x: f"{x:.4f}"))
    print(f"\nWrote {len(raw)} replicate rows; figures at 300 dpi; seed={base_seed}.")


if __name__ == "__main__":
    main()
